def test_write_refuses_a_write_that_fails(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A full disk surfaces when the buffer is written, and the `.tmp` stays."""
    path = tmp_path / "settings.json"

    class FullDisk:
        def __enter__(self) -> Self:
            return self

        def __exit__(self, *_args: object) -> None:
            return None

        def write(self, _data: bytes) -> None:
            raise OSError

    monkeypatch.setattr("builtins.open", lambda *_a, **_k: FullDisk())
    with pytest.raises(ValueError, match=r".") as refused:
        write_settings(str(path), {})
