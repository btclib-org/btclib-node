"""`settings_file.py`: Core's UniValue reader and writer, and `settings.json`.

Every accepted and refused text below was run through `bitcoind` v31.1.0
(`-regtest -help`, which reads and writes the file and exits), and each
file written was compared byte for byte.
"""

