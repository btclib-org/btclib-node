_INVALID = "does not contain valid JSON. This may be caused by a crash"
_WARNING = (
    f"This file is automatically generated and updated by {CLIENT_NAME}. "
    "Please do not edit this file while the node is running, as any changes "
    "might be ignored or overwritten."
)


def _read(tmp_path: Path, content: str | bytes) -> dict[str, Json]:
    path = tmp_path / "settings.json"
    path.write_bytes(content.encode() if isinstance(content, str) else content)
    return read_settings(str(path))


def _refusal(tmp_path: Path, content: str | bytes) -> str:
    with pytest.raises(ValueError, match=r".") as refused:
        _read(tmp_path, content)
    # Core prints the path as the platform spells it, `\` on Windows.
    return str(refused.value).replace(str(tmp_path / "settings.json"), "<FILE>")


def _written(tmp_path: Path, content: str | bytes) -> str:
    """Return what `content` is written back as: Core's `-help` run."""
    path = tmp_path / "settings.json"
    write_settings(str(path), _read(tmp_path, content))
    return path.read_bytes().decode("utf-8")


def _file(*lines: str) -> str:
    """Return a settings file under the `_warning_` key, `lines` after it.

    Its line ends are the platform's, as the file is written in text mode.
    """
    warning = f'    "_warning_": "{_WARNING}"'
    body = ",\n".join([warning, *lines])
    return ("{\n" + body + "\n}\n").replace("\n", os.linesep)


